#!/usr/bin/env node
/**
 * Emits the canonical schemas from /schemas as a TypeScript module so the
 * contracts package works identically in Node, workers and the browser
 * without filesystem access. /schemas remains the single source of truth.
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const schemaDir = join(repoRoot, "schemas");
const outFile = join(repoRoot, "packages", "contracts", "src", "schemas.generated.ts");

const files = [
  ["structure", "structure.schema.json"],
  ["material", "material.schema.json"],
  ["simulation", "simulation.schema.json"],
  ["job", "job.schema.json"],
  ["result", "result.schema.json"],
  ["provenance", "provenance.schema.json"],
  ["engine", "engine.schema.json"],
];

const entries = [];
for (const [key, file] of files) {
  const raw = await readFile(join(schemaDir, file), "utf8");
  const parsed = JSON.parse(raw);
  entries.push(`  ${JSON.stringify(key)}: ${JSON.stringify(parsed)},`);
}

const banner = `// AUTO-GENERATED by scripts/sync-schemas.mjs — do not edit by hand.
// Source of truth: /schemas/*.schema.json
/* eslint-disable */
`;
const content = `${banner}export const schemas = {\n${entries.join("\n")}\n} as const;\n\nexport type SchemaName = keyof typeof schemas;\n`;

await mkdir(dirname(outFile), { recursive: true });
await writeFile(outFile, content, "utf8");
console.log(`[schemas] wrote ${outFile} (${files.length} schemas)`);
